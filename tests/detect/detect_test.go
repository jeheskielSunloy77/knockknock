func TestNormalizeRedirectChainPreservesHeaders(t *testing.T) {
	raw := "HTTP/2 302 Found\r\nSet-Cookie: _abck=1\r\nLocation: /home\r\n\r\n" +
		"redirecting\r\nHTTP/2 200 OK\r\nContent-Type: text/html\r\n\r\n<html>home</html>"

	got := detect.Normalize([]byte(raw), detect.DefaultBodyCap)
	for _, want := range []string{
		"S:302",
		"S:200",
		"H:set-cookie:_abck=1",
		"H:location:/home",
		"B:<html>home</html>",
	} {
		if !strings.Contains(got, want) {
			t.Fatalf("Normalize() missing %q in:\n%s", want, got)
		}
	}
}

func TestMatchReturnsSortedNamedGroups(t *testing.T) {
	re := regexp.MustCompile(`(?m)(?P<z_vendor>B:z)|(?P<a_vendor>H:x-a:1)`)
	raw := []byte("HTTP/1.1 200 OK\r\nX-A: 1\r\n\r\nz")
	got := detect.Match(raw, re, detect.DefaultBodyCap)
	want := []string{"a_vendor", "z_vendor"}
	if !reflect.DeepEqual(got, want) {
		t.Fatalf("Match() = %v, want %v", got, want)
	}
}

func TestDetectInvalidRegex(t *testing.T) {
	if _, err := detect.Detect([]byte("body"), "(", detect.DefaultBodyCap); err == nil {
		t.Fatal("Detect() error = nil, want invalid regex error")
	}
}

func TestEmbeddedArtifactsInSync(t *testing.T) {
	pattern, err := signature.Compile("../../signatures", "")
	if err != nil {
		t.Fatalf("Compile(): %v", err)
	}
	if strings.TrimSpace(detect.PresenceRegexText) != pattern {
		t.Fatal("regex_presence.re2.txt is stale; run: go run ./cmd/knockknock compile")
	}

	challengePattern, err := signature.CompileChallenge("../../signatures", "")
	if err != nil {
		t.Fatalf("CompileChallenge(): %v", err)
	}
	if strings.TrimSpace(detect.ChallengeRegexText) != challengePattern {
		t.Fatal("regex_challenge.re2.txt is stale; run: go run ./cmd/knockknock compile")
	}
}

func TestNewVendorsDetection(t *testing.T) {
	tests := []struct {
		name       string
		raw        string
		wantVendor string
		challenge  bool
	}{
		{"radware cookie", "HTTP/1.1 200 OK\r\nSet-Cookie: __ss_uuid=123\r\n\r\nok", "radware", false},
		{"radware challenge", "HTTP/1.1 403 Forbidden\r\n\r\nWhy did this happen? shieldsquare", "radware", true},
		{"signal_sciences header", "HTTP/1.1 200 OK\r\nX-SigSci-Tags: malicious\r\n\r\nok", "signal_sciences", false},
		{"signal_sciences challenge", "HTTP/1.1 403 Forbidden\r\n\r\nProtected by Signal Sciences", "signal_sciences", true},
		{"azure_waf header", "HTTP/1.1 200 OK\r\nX-Azure-Ref: 0abcdef\r\n\r\nok", "azure_waf", false},
		{"azure_waf challenge", "HTTP/1.1 403 Forbidden\r\n\r\nOur apologies, but the web page you are looking for has been blocked", "azure_waf", true},
		{"fingerprint script", "HTTP/1.1 200 OK\r\n\r\n<script src=\"https://fpcdn.io/v3/key\"></script>", "fingerprint", false},
		{"aliyun_waf cookie", "HTTP/1.1 200 OK\r\nSet-Cookie: acw_tc=12345\r\n\r\nok", "aliyun_waf", false},
		{"aliyun_waf challenge", "HTTP/1.1 200 OK\r\nSet-Cookie: acw_sc__v2=12345\r\n\r\nok", "aliyun_waf", true},
		{"forter cookie", "HTTP/1.1 200 OK\r\nSet-Cookie: ftr_blist=abc\r\n\r\nok", "forter", false},
		{"castle header", "HTTP/1.1 200 OK\r\nX-Castle-Client-Id: 1234\r\n\r\nok", "castle", false},
		{"sift script", "HTTP/1.1 200 OK\r\n\r\n<script src=\"https://cdn.sift.com/s.js\"></script>", "sift", false},
		{"kount script", "HTTP/1.1 200 OK\r\n\r\n<script src=\"https://ssl.kount.net/ka.js?kount\"></script>", "kount", false},
		{"modsecurity header", "HTTP/1.1 403 Forbidden\r\nServer: mod_security/2.9\r\n\r\nblocked", "modsecurity", false},
		{"modsecurity challenge", "HTTP/1.1 403 Forbidden\r\n\r\nThis error was generated by Mod_Security", "modsecurity", true},
		{"barracuda cookie", "HTTP/1.1 200 OK\r\nSet-Cookie: BNI_persistence=123\r\n\r\nok", "barracuda", false},
		{"barracuda challenge", "HTTP/1.1 403 Forbidden\r\n\r\nYou are attempting to access a forbidden site - Barracuda Networks", "barracuda", true},
		{"netscaler cookie", "HTTP/1.1 200 OK\r\nSet-Cookie: ns_af=123\r\n\r\nok", "netscaler", false},
		{"fortiweb cookie", "HTTP/1.1 200 OK\r\nSet-Cookie: FORTIWAFID=123\r\n\r\nok", "fortiweb", false},
		{"fortiweb challenge", "HTTP/1.1 403 Forbidden\r\n\r\nThe page you are trying to access is restricted FortiWeb", "fortiweb", true},
		{"altcha element", "HTTP/1.1 200 OK\r\n\r\n<altcha-widget challengeurl=\"/altcha\"></altcha-widget>", "altcha", false},
		{"mcaptcha element", "HTTP/1.1 200 OK\r\n\r\n<m-captcha data-mcaptcha_url=\"https://mcaptcha.org\"></m-captcha>", "mcaptcha", false},
	}

	for _, tt := range tests {
		t.Run(tt.name, func(t *testing.T) {
			regexText := detect.PresenceRegexText
			if tt.challenge {
				regexText = detect.ChallengeRegexText
			}
			verdict, err := detect.Detect([]byte(tt.raw), regexText, detect.DefaultBodyCap)
			if err != nil {
				t.Fatalf("Detect() failed: %v", err)
			}
			found := false
			for _, v := range verdict.Vendors {
				if v == tt.wantVendor {
					found = true
					break
				}
			}
			if !found {
				t.Errorf("Detect() vendors = %v, want to contain %q", verdict.Vendors, tt.wantVendor)
			}
		})
	}
}

